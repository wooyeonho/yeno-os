test('relationshipMemoryPointer is re-derived fresh every heartbeat from the most recent relationship memory event, never an independently settable field', () => {
  const state = baseState();
  const older = createMemoryEvent({type: 'relationship', text: '첫 상호작용', confidence: 0.5, projectId: null, questId: null, sourceRefs: []}, state, {at: '2026-01-01T00:00:00.000Z'});
  state.memoryEvents = addMemoryEvent(state.memoryEvents, older, state);
  const {core: core1} = evaluateHeartbeat(initialCoreState(), state, {at: at()});
  assert.equal(core1.relationshipMemoryPointer, older.id);

  const newer = createMemoryEvent({type: 'relationship', text: '더 최근 상호작용', confidence: 0.5, projectId: null, questId: null, sourceRefs: []}, state, {at: '2026-06-01T00:00:00.000Z'});
  state.memoryEvents = addMemoryEvent(state.memoryEvents, newer, state);
  const {core: core2} = evaluateHeartbeat(core1, state, {at: at()});
  assert.equal(core2.relationshipMemoryPointer, newer.id);
  validateCoreState(core2, state);
});

test('heartbeatLog is bounded and always keeps the most recent entries, never grows unbounded', () => {
  const state = baseState();
  let core = initialCoreState();
  for (let i = 0; i < 30; i++) {
    core = evaluateHeartbeat(core, state, {at: new Date(Date.now() + i * 1000).toISOString()}).core;
  }
  assert.equal(core.heartbeatCount, 30);
  assert.ok(core.heartbeatLog.length <= 20);
  assert.equal(core.heartbeatLog.length, 20);
  validateCoreState(core, state);
});

test('heartbeat entries record an explicit wake trigger, separate from the changed-fields reason, defaulting to the honest state_changed', () => {
  const state = baseState();
  const {entry: defaultEntry} = evaluateHeartbeat(initialCoreState(), state, {at: at()});
  assert.equal(defaultEntry.trigger, 'state_changed', 'omitting trigger must fall back to the honest default, never imply a specific cause it was not given');

  for (const trigger of HEARTBEAT_TRIGGERS) {
    const {entry, core} = evaluateHeartbeat(initialCoreState(), state, {at: at(), trigger});
    assert.equal(entry.trigger, trigger);
    validateCoreState(core, state);
  }

  assert.throws(() => evaluateHeartbeat(initialCoreState(), state, {at: at(), trigger: 'not_a_real_trigger'}), BlackholeCoreError);
});

test('the wake trigger (why it woke) is independent of the reason/changedFields (what it noticed): a real state change under runtime_started still names runtime_started', () => {
  const jobId = randomUUID();
  const state = baseState({jobs: [job(jobId, {status: 'running'})]});
  const {entry} = evaluateHeartbeat(initialCoreState(), state, {at: at(), trigger: 'runtime_started'});
  assert.equal(entry.trigger, 'runtime_started');
  assert.ok(entry.changedFields.includes('activity'), 'the projection still records what changed');
  assert.match(entry.reason, /changed: activity/);

  // And a no-op heartbeat under a real trigger still names that trigger,
  // never manufacturing a change that did not happen.
  const core1 = evaluateHeartbeat(initialCoreState(), state, {at: at(), trigger: 'runtime_started'}).core;
  const {entry: entry2} = evaluateHeartbeat(core1, state, {at: at(), trigger: 'owner_command'});
  assert.equal(entry2.trigger, 'owner_command');
  assert.equal(entry2.reason, 'observed, no change');
});

