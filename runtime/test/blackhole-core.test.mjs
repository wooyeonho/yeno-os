  assert.deepEqual([...ACTIVITY_STATES].sort(), ['absorbing', 'blocked', 'emergency', 'executing', 'idle', 'leveling', 'listening', 'offline', 'planning', 'remembering', 'thinking', 'verifying'].sort());
