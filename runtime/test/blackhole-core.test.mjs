// BLACKHOLE Living Core, Phase A — persistent self + event-driven heartbeat +
// canonical Memory Event primitive. These are pure-function tests against the
// exact projection/validation logic store.mjs and server.mjs wire in; the
// restart-persistence and emergency-stop behaviour are covered end-to-end in
// blackhole-core-server.test.mjs against the real store/server.

const at = () => new Date().toISOString();
function baseState(overrides = {}) {
  return {emergencyStop: false, jobs: [], quests: [], projects: [], outcomes: [], sources: [], capabilities: {entries: []}, memoryEvents: [], ...overrides};
}
function project(id, overrides = {}) {
  const t = at();
  return {id, name: 'P', repositoryUrl: '', summary: '', nextAction: '', status: 'active', version: 1, createdAt: t, updatedAt: t, ...overrides};
}
function quest(id, jobId, overrides = {}) {
  const t = at();
  return {id, driveId: 'sloth', drive: 'sloth', projectId: null, status: 'queued', jobId, updatedAt: t, createdAt: t, goal: 'g', successCriterion: 's', baseline: 'b', ...overrides};
}
function job(id, overrides = {}) {
  const t = at();
  return {id, status: 'queued', updatedAt: t, createdAt: t, artifacts: [], ...overrides};
}

test('initialCoreState is idle, empty and validates against an empty state', () => {
  const state = baseState();
  const core = initialCoreState();
  assert.equal(core.schemaVersion, CORE_SCHEMA_VERSION);
  assert.equal(core.activity, 'idle');
  assert.equal(core.missionQuestId, null);
  assert.equal(core.dominantDriveId, null);
  assert.deepEqual(core.activeShadowIds, []);
  assert.equal(core.recentArtifactRef, null);
  assert.equal(core.verifiedResultRef, null);
  assert.equal(core.heartbeatCount, 0);
  assert.equal(core.lastHeartbeatAt, null);
  validateCoreState(core, state);
});

test('a stable Persistent Self identity is generated once and never regenerated by later heartbeats', () => {
  const state = baseState();
  const core0 = initialCoreState('2026-01-01T00:00:00.000Z');
  assert.match(core0.identity.id, /^[0-9a-f-]{36}$/);
  assert.equal(core0.identity.name, 'BLACKHOLE');
  assert.equal(core0.identity.createdAt, '2026-01-01T00:00:00.000Z');
  validateCoreState(core0, state);

  const {core: core1} = evaluateHeartbeat(core0, state, {at: '2026-01-01T00:01:00.000Z'});
  assert.deepEqual(core1.identity, core0.identity, 'identity must survive an ordinary heartbeat unchanged');
  const {core: core2} = evaluateHeartbeat(core1, state, {at: '2026-01-01T00:02:00.000Z', trigger: 'owner_command'});
  assert.deepEqual(core2.identity, core0.identity, 'identity must survive across many heartbeats and triggers unchanged');

  // Two independently created identities must never collide.
  const other = createCoreIdentity('2026-01-01T00:00:00.000Z');
  assert.notEqual(other.id, core0.identity.id);
});

test('validateCoreState rejects a tampered or malformed identity', () => {
  const state = baseState();
  const core = initialCoreState();
  assert.throws(() => validateCoreState({...core, identity: {...core.identity, id: 'not-a-uuid'}}, state), BlackholeCoreError);
  assert.throws(() => validateCoreState({...core, identity: {...core.identity, name: ''}}, state), BlackholeCoreError);
  assert.throws(() => validateCoreState({...core, identity: {...core.identity, createdAt: 'not-a-date'}}, state), BlackholeCoreError);
  assert.throws(() => validateCoreState({...core, identity: {id: core.identity.id}}, state), BlackholeCoreError, 'missing identity fields must fail closed');
});

