import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomBytes,randomUUID,createHash} from 'node:crypto';
import {mkdtempSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {start} from '../runtime/server.mjs';

const require=createRequire(new URL('../apps/controller/package.json',import.meta.url));
const {chromium}=require('playwright');
const output=new URL('../build-artifacts/jarvis-e2e-20260927/',import.meta.url);
mkdirSync(output,{recursive:true});
const dataDir=mkdtempSync(join(tmpdir(),'blackhole-jarvis-local-only-'));
const token=randomBytes(32).toString('hex');
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const answer='합성 대화 응답. 실제 시각은 확인하지 않았어.';
let core,browser,modelCalls=0;
const report={evidenceClass:'SYNTHETIC_LOCAL_PROVIDER_BROWSER_E2E',networkModelCalls:0,modelCalls:0,chat:null,work:null};
try{
  core=await start({host:'127.0.0.1',port:0,dataDir,token,env:{YENO_AGENT_PROVIDER:'auto',YENO_AGENT_DAILY_CALL_LIMIT:'4',YENO_LOCAL_MODEL:'synthetic-local'},agentFetch:async()=>{
    modelCalls++;
    return new Response(JSON.stringify({choices:[{finish_reason:'stop',message:{content:answer}}],usage:{prompt_tokens:5,completion_tokens:12}}),{status:200,headers:{'content-type':'application/json'}});
  }});
  const origin=`http://127.0.0.1:${core.server.address().port}`;
  const settings=await fetch(origin+'/api/settings',{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify({requestId:randomUUID(),modules:{ai:true}})});
  assert.equal(settings.status,200);
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({baseURL:origin,viewport:{width:400,height:840}});
  const page=await context.newPage();
  const commandStatuses=[];
  page.on('response',response=>{if(new URL(response.url()).pathname==='/api/commands')commandStatuses.push(response.status());});
  await page.goto('/jarvis');
  await page.locator('#device-connect').click();
  const reference=page.locator('#device-connect-reference');
  await reference.waitFor({state:'visible'});
  const requestId=await reference.textContent();
  const approval=await context.request.post('/api/web/pairing/approve',{headers:{Authorization:`Bearer ${token}`,Origin:origin},data:{requestId}});
  assert.equal(approval.status(),200);
  await page.locator('#pair-screen').waitFor({state:'hidden'});
  await page.locator('#command-mode').click();
  assert.equal(await page.locator('#command-mode').getAttribute('aria-pressed'),'true');
  await page.locator('#in').fill('지금 몇 시야?');
  await page.locator('#send').click();
  await page.waitForFunction(text=>document.querySelector('#line')?.textContent===text,answer,{timeout:12000});
  await page.waitForFunction(()=>document.querySelector('#model')?.textContent?.includes('local · synthetic-local'),null,{timeout:12000});
  const stateResponse=await context.request.get('/api/state',{headers:{'X-Yeno-Browser':'1'}});
  const state=await stateResponse.json();
  const job=state.jobs.find(item=>item.title==='음성 대화 · 지금 몇 시야?');
  assert.equal(job?.status,'completed');
  assert.equal(job.provider,'local');
  assert.equal(job.artifacts.length,1);
  const chatImage='a2-result.png';
  await page.screenshot({path:fileURLToPath(new URL(chatImage,output)),fullPage:true});
  report.chat={jobId:job.id,status:job.status,provider:job.provider,model:job.model,screenshot:{file:chatImage,sha256:sha256(readFileSync(new URL(chatImage,output)))} };
  writeFileSync(new URL('a2-job.json',output),JSON.stringify(report.chat,null,2));
  await page.locator('#command-mode').click();
  await page.locator('#in').fill('오늘 할 일 세 개 정리해줘');
  await page.locator('#send').click();
  await page.waitForFunction(()=>document.querySelector('#line')?.textContent?.includes('요청은 목표로 보관했어'),null,{timeout:12000});
  await page.waitForFunction(()=>!document.querySelector('#line')?.classList.contains('fade'));
  await page.waitForTimeout(350);
  assert.ok((await page.locator('#line').textContent()).includes('작업용 모델이 없어'));
  const questsResponse=await context.request.get('/api/quests',{headers:{'X-Yeno-Browser':'1'}});
  const quests=await questsResponse.json();
  const saved=quests.quests.find(quest=>quest.goal==='오늘 할 일 세 개 정리해줘');
  assert.equal(saved?.status,'proposed');
  assert.deepEqual(commandStatuses.slice(-2),[409,201]);
  assert.equal(modelCalls,1,'A3 must not call the local model for a goal');
  const workImage='a3-result.png';
  await page.screenshot({path:fileURLToPath(new URL(workImage,output)),fullPage:true});
  report.work={blockedStatus:409,savedStatus:201,savedQuestId:saved.id,modelCallsAfter:modelCalls,screenshot:{file:workImage,sha256:sha256(readFileSync(new URL(workImage,output)))} };
  report.modelCalls=modelCalls;
  writeFileSync(new URL('a3-response.json',output),JSON.stringify(report.work,null,2));
  writeFileSync(new URL('local-only-report.json',output),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
}finally{
  await browser?.close();
  const closed=core?new Promise(resolve=>core.server.once('close',resolve)):null;
  core?.shutdown();
  await closed;
  await rm(dataDir,{recursive:true,force:true});
}
