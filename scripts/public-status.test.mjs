import test from 'node:test';
import assert from 'node:assert/strict';
import {statusTable,updateReadme} from './public-status.mjs';

test('README status table is generated from registry rows only',()=>{
  const status={schemaVersion:1,subsystems:[{id:'S20',implementation:'partial',evidence:['local','synthetic'],sourceSection:172,artifact:'build-artifacts/s20/report.json',sha256:'a'.repeat(64)}]};
  const readme='before\n<!-- STATUS:BEGIN generated by scripts/public-status.mjs -->\nold\n<!-- STATUS:END -->\nafter';
  const updated=updateReadme(readme,status);
  assert.match(updated,/S20 \| partial \| local, synthetic/);
  assert.doesNotMatch(updated,/\nold\n/);
  assert.equal(updateReadme(updated,status),updated);
  assert.match(statusTable(status),/SHA-256 a{12}/);
});

test('malformed registry row is rejected',()=>{
  assert.throws(()=>statusTable({schemaVersion:1,subsystems:[{id:'<script>',implementation:'implemented',evidence:[]}]}),/Invalid status row/);
});
