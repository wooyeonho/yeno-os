import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const begin='<!-- STATUS:BEGIN generated by scripts/public-status.mjs -->';
const end='<!-- STATUS:END -->';
const safe=value=>String(value).replace(/[|\r\n]/g,' ');

export function statusTable(status){
  if(status.schemaVersion!==1||!Array.isArray(status.subsystems))throw Error('Invalid status registry');
  const rows=status.subsystems.map(row=>{
    if(!/^[A-Za-z][A-Za-z0-9-]{1,40}$/.test(row.id)||!['implemented','partial','not_implemented'].includes(row.implementation)||!Array.isArray(row.evidence))throw Error('Invalid status row');
    const receipt=row.artifact?`[§${row.sourceSection} · SHA-256 ${row.sha256.slice(0,12)}…](${encodeURI(row.artifact)})`:`§${row.sourceSection} · 없음`;
    return `| ${safe(row.id)} | ${safe(row.implementation)} | ${safe(row.evidence.join(', '))} | ${receipt} |`;
  });
  return [begin,'| 기능 | 구현 | 근거 유형 | 실행 기록·산출물 |','| --- | --- | --- | --- |',...rows,end].join('\n');
}

export function updateReadme(readme,status){
  const block=statusTable(status),start=readme.indexOf(begin),stop=readme.indexOf(end);
  if(start<0||stop<start)throw Error('Missing generated status markers');
  return readme.slice(0,start)+block+readme.slice(stop+end.length);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const mode=process.argv[2];
  if(!['--write','--check'].includes(mode))throw Error('Usage: node scripts/public-status.mjs --write|--check');
  const readmePath=path.join(root,'README.md');
  const current=fs.readFileSync(readmePath,'utf8');
  const status=JSON.parse(fs.readFileSync(path.join(root,'docs','STATUS.json'),'utf8'));
  const next=updateReadme(current,status);
  if(mode==='--write')fs.writeFileSync(readmePath,next);
  else if(current!==next)throw Error('README status table is stale');
  console.log(`public status ${mode.slice(2)}: ${status.subsystems.length} rows`);
}
