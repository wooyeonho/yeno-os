import assert from 'node:assert/strict';
import {createHash,randomBytes,randomUUID} from 'node:crypto';
import {createRequire} from 'node:module';
import {mkdtempSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {start} from '../runtime/server.mjs';
import {openStore} from '../runtime/lib/store.mjs';
import {missionStatus} from '../runtime/lib/shadow-army.mjs';
import {exportBackup,decryptBackup} from '../runtime/lib/backup.mjs';

const out=new URL('../build-artifacts/s11-20261001/',import.meta.url);mkdirSync(out,{recursive:true});
const require=createRequire(new URL('../apps/controller/package.json',import.meta.url));
const {chromium}=require('playwright');
const dataDir=mkdtempSync(join(tmpdir(),'blackhole-s11-profile-live-'));
const token=randomBytes(32).toString('hex');
const env={YENO_AGENT_PROVIDER:'auto',YENO_AGENT_DAILY_CALL_LIMIT:'20',YENO_LOCAL_MODEL:'synthetic-local',YENO_NVIDIA_MODEL:'synthetic-remote',YENO_NVIDIA_API_KEY:'synthetic-fixture-only'};
const verdict={verdict:'pass',confidence:0.9,criteria:[{criterion:'검증 가능한 산출물',status:'met',reason:'저장된 내용과 일치',evidenceRefs:['실제 Shadow 산출물 본문']}],summary:'저장된 산출물과 근거가 일치함'};
const calls=[];
const agentFetch=async(_url,request)=>{
  const body=JSON.parse(request.body);calls.push({model:body.model,toolNames:body.tools?.map(t=>t.function?.name??t.name)??[]});
  const semantic=body.messages.some(message=>typeof message.content==='string'&&message.content.includes('independent semantic verifier'));
  return new Response(JSON.stringify({choices:[{finish_reason:'stop',message:{content:semantic?JSON.stringify(verdict):'실제 Shadow 산출물 본문',tool_calls:[]}}],usage:{prompt_tokens:12,completion_tokens:8}}),{headers:{'Content-Type':'application/json'}});
};
let core,browser;
const close=async()=>{if(!core)return;const finished=new Promise(resolve=>core.server.once('close',resolve));core.shutdown();await finished;core=null;};
const report={evidenceClass:'SYNTHETIC_PROVIDERS_REAL_LOCAL_HTTP_EDGE',ownerOnly:false,disconnectedRejected:false,connectorCheck:null,profileRestarted:false,assigned:null,storedExcluded:false,backupProfileCount:null,modelCalls:0,firstMissionModels:null,ui:null};
try{
  core=await start({host:'127.0.0.1',port:0,dataDir,token,env,agentFetch});
  const origin=()=>`http://127.0.0.1:${core.server.address().port}`;
  const get=async route=>{const response=await fetch(origin()+route,{headers:{Authorization:`Bearer ${token}`}});return {status:response.status,body:await response.json()};};
  const post=async(route,data)=>{const response=await fetch(origin()+route,{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify({requestId:randomUUID(),...data})});return {status:response.status,body:await response.json()};};
  const wait=async id=>{for(let i=0;i<400;i++){const m=missionStatus(id,openStore(dataDir).state);if(['completed','failed'].includes(m?.phase))return m;await new Promise(resolve=>setTimeout(resolve,20));}throw Error('mission did not settle');};
  report.ownerOnly=(await fetch(origin()+'/api/shadow-army/profiles')).status!==200;
  assert.equal(report.ownerOnly,true);
  const project=await post('/api/projects',{name:'S11 격리 프로필',status:'active'});assert.equal(project.status,201);
  const first=await post('/api/shadow-army/missions',{projectId:project.body.project.id,goal:'프로필 출처 검증',successCriterion:'검증 가능한 산출물 1개'});
  assert.equal(first.status,201,JSON.stringify(first.body));
  assert.equal((await post('/api/shadow-army/major',{missionId:first.body.missionId})).status,200);
  assert.equal((await wait(first.body.missionId)).phase,'completed');
  report.firstMissionModels=Object.fromEntries(openStore(dataDir).state.jobs.filter(job=>job.shadowAssignment?.missionId===first.body.missionId&&job.agentJournal).map(job=>[job.shadowAssignment.role,job.agentJournal.model]));
  assert.equal(report.firstMissionModels.scout,'synthetic-local');
  assert.equal(report.firstMissionModels.semanticVerifier,'synthetic-remote');
  const roster=(await get('/api/shadow-army/roster')).body.roster;
  const scout=roster.entries.find(entry=>entry.role==='scout');assert.ok(scout);
  const attempted={shadowId:scout.id,modelBinding:'local',toolScope:['project_sources'],budgetShare:1};
  const before=await post('/api/shadow-army/profiles',attempted);
  report.disconnectedRejected=before.status===409;assert.equal(report.disconnectedRejected,true);
  const checked=await post('/api/connectors/ollama/check',{});
  assert.equal(checked.status,200,JSON.stringify(checked.body));
  report.connectorCheck=checked.body.connector?.status;
  assert.equal(report.connectorCheck,'connected');
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({baseURL:origin(),viewport:{width:400,height:840},reducedMotion:'reduce'});
  const page=await context.newPage();await page.goto('/jarvis');await page.locator('#device-connect').click();
  const reference=await page.locator('#device-connect-reference').textContent();
  const approval=await context.request.post('/api/web/pairing/approve',{headers:{Authorization:`Bearer ${token}`,Origin:origin()},data:{requestId:reference}});
  assert.equal(approval.status(),200);await page.locator('#pair-screen').waitFor({state:'hidden'});
  await page.locator('#control-toggle').click();
  await page.locator('#shadow-roster-list .shadow-profile-open').first().click();
  await page.locator('#shadow-profile-panel').waitFor({state:'visible'});
  await page.locator('#shadow-profile-model').selectOption('local');
  await page.locator('#shadow-profile-budget').selectOption('1');
  const read=page.locator('#shadow-profile-tools input[value="project_read"]');if(await read.count())await read.uncheck();
  await page.locator('#shadow-profile-form button[type="submit"]').click();
  await page.waitForFunction(()=>document.querySelector('#shadow-profile-status')?.textContent?.includes('저장됨'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const image='shadow-profile-400.png';await page.screenshot({path:fileURLToPath(new URL(image,out)),fullPage:true});
  report.ui={viewport:'400x840',image,sha256:createHash('sha256').update(readFileSync(new URL(image,out))).digest('hex'),provider:await page.locator('#shadow-profile-model').inputValue()};
  await browser.close();browser=null;
  await close();
  core=await start({host:'127.0.0.1',port:0,dataDir,token,env,agentFetch});
  const profiles=(await get('/api/shadow-army/profiles')).body.profiles;
  report.profileRestarted=profiles.some(item=>item.shadowId===scout.id&&item.modelBinding==='local'&&item.budgetShare===1);
  assert.equal(report.profileRestarted,true);
  // Connector status is process-local and expires on restart. A pinned model
  // cannot silently bypass that check when a new mission is dispatched.
  const held=await post('/api/shadow-army/missions',{projectId:project.body.project.id,goal:'재시작 뒤 확인',successCriterion:'산출물'});
  assert.equal(held.status,409);
  assert.equal((await post('/api/connectors/ollama/check',{})).body.connector.status,'connected');
  const second=await post('/api/shadow-army/missions',{projectId:project.body.project.id,goal:'재시작 뒤 확인',successCriterion:'산출물'});
  assert.equal(second.status,201,JSON.stringify(second.body));
  const worker=openStore(dataDir).state.jobs.find(job=>job.shadowAssignment?.missionId===second.body.missionId&&job.shadowAssignment.role==='scout');
  assert.equal(worker.shadowAssignment.preferredShadowId,scout.id);
  assert.equal(worker.selectedProvider,'local');assert.equal(worker.callLimit,1);
  assert.deepEqual(worker.shadowAssignment.toolScope,['project_sources']);
  report.assigned={shadowId:scout.id,provider:worker.selectedProvider,callLimit:worker.callLimit,toolScope:worker.shadowAssignment.toolScope};
  assert.equal((await wait(second.body.missionId)).phase,'completed');
  assert.equal((await post('/api/shadow-army/store',{id:scout.id,stored:true})).status,200);
  const third=await post('/api/shadow-army/missions',{projectId:project.body.project.id,goal:'보관된 정찰자 제외',successCriterion:'산출물'});
  assert.equal(third.status,201);
  const next=openStore(dataDir).state.jobs.find(job=>job.shadowAssignment?.missionId===third.body.missionId&&job.shadowAssignment.role==='scout');
  report.storedExcluded=!next.shadowAssignment.preferredShadowId;
  assert.equal(report.storedExcluded,true);
  const state=openStore(dataDir).state,key=randomBytes(32);
  report.backupProfileCount=decryptBackup(exportBackup({state,dataDir,key}),key).state.shadowProfiles.entries.length;
  assert.equal(report.backupProfileCount,1);
  report.modelCalls=calls.length;
  writeFileSync(new URL('shadow-profile-report.json',out),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
}finally{
  await browser?.close();
  await close();
  if(dataDir.startsWith(tmpdir())&&dataDir.includes('blackhole-s11-profile-live-'))await rm(dataDir,{recursive:true,force:true});
}
